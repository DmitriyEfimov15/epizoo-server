"""Чистые текстовые преобразования без доступа к БД и справочникам."""

import re


def clean_text(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\xad", "")).strip()


def normalize_locality(text: str) -> str:
    text = clean_text(text).lower().replace("ё", "е")
    text = re.sub(
        r"^(?:село|села|селе|деревня|деревни|деревне|поселок|поселка|поселке|"
        r"город|города|городе|хутор|станица|р\.?\s?п\.?|пгт\.?|птг\.?|"
        r"ст-ца\.?|ст\.?|пос\.?|дер\.?|с\.|д\.|п\.|г\.|хут\.?|х\.)\s+",
        "",
        text,
    )
    return clean_text(re.sub(r"[^\w\s-]", " ", text))


def extract_species(text: str) -> list[str]:
    text = text.lower().replace("ё", "е")
    patterns = {
        "cattle": r"\bкрс\b|крупн\w*\s+рогат\w*\s+скот|"
        r"\bкоров(?:а|ы|у|е|ой|ам|ами|ах)\b|\bбык(?:а|и|ов|у|ом)?\b|\bтеленок\b",
        "small_ruminants": r"\bмрс\b|\bкоз(?:а|ы|у|е|ой|ам|ами|ах|ел|лы|лов)\b|"
        r"\bов(?:ца|цы|ец|цу|це|цой|цами|цам|цах)\b|мелк\w*\s+рогат",
        "pigs": r"свин|кабан",
        "poultry": r"птиц|куриц|кур\b|утк|гус[ьи]",
        "horses": r"лошад|кон[ьи]|жереб",
        "bees": r"пчел|пасек|нозематоз|варроатоз",
        "rabbits": r"кролик",
        "carnivores": r"собак|кошк|\bкот\b|\bлис(?:а|ы|у|е|ой)\b|"
        r"\bлисиц(?:а|ы|у|е|ей)\b|плотояд|куниц|енот|волк",
        "wildlife": r"дик\w*\s+(?:живот|фаун|кабан)|\bлис(?:а|ы|у|е|ой)\b|"
        r"\bлисиц(?:а|ы|у|е|ей)\b|куниц|енот|волк|"
        r"медвед|косул|бобр|\bлос(?:ь|я|и|ей)\b",
    }
    return [slug for slug, pattern in patterns.items() if re.search(pattern, text)]


def disease_heading(line: str) -> tuple[str, str] | None:
    line = clean_text(line)
    if (
        not re.match(r"[А-ЯЁ]", line)
        or len(line) > 105
        or not re.match(
            r"^(?:Бешенство|Бруцелл[её]з|Лейкоз|Лептоспироз|Сибирская язва|"
            r"Африканская чума|Классическая чума|Грипп птиц|Высокопатогенный грипп|"
            r"Случная болезнь|Инфекционная анемия|Трихинелл?[её]з|Эмфизематозный|"
            r"Нодулярный|Заразный узелковый|Хламидиоз|Варроатоз|Нозематоз|"
            r"Чума плотоядных|Пастерелл[её]з|Парагрипп-3|Пироплазмоз|"
            r"Оспа|Болезнь Ньюкасла|Туберкул[её]з|Ящур|Болезнь Ауески|"
            r"Инфекционный ринотрахеит|Инфекционный бронхит|Миксоматоз|"
            r"Вирусная геморрагическая|Сальмонелл[её]з)\b",
            line,
            re.I,
        )
    ):
        return None
    if ":" in line or re.search(r"\b(?:по|на|установлены|отменены|область)\b", line):
        return None
    lifted = bool(re.search(r"сняти[ея]\s+карантина", line, re.I))
    disease = re.sub(
        r",?\s*(?:сняти[ея]|продление)\s+карантина.*",
        "",
        line,
        flags=re.I,
    ).strip()
    return disease, "quarantine_lifted" if lifted else "quarantine_set"


def ignored_section(line: str) -> bool:
    return "профилактические мероприятия" in line.lower() or bool(
        re.match(
            r"^(?:Профилактические мероприятия|Деятельность|Работа со скотомогильниками|"
            r"Научные публикации|Лабораторное подтверждение|Лабораторная деятельность|"
            r"Балл|ИНТЕРПРЕТАЦИЯ)",
            line,
        )
    )
